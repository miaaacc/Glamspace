// Traduce el nombre de una categoría (viene del backend en español).
// Si no hay traducción, devuelve el nombre original.
export function traducirCategoria(t, nombre) {
  if (!nombre) return nombre
  const clave = `cat.${nombre}`
  const traducida = t(clave)
  return traducida === clave ? nombre : traducida
}
